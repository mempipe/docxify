// Generate the browser's wire types from the same Rust types that serde serializes.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

const schema = JSON.parse(execFileSync("cargo", [
  "run", "--quiet", "--features", "schema", "-p", "docx-engine", "--example", "web_schema",
], { cwd: new URL("../", import.meta.url), encoding: "utf8" }));

// The two serde flatten attributes put the node kind, optional formatting
// and common fields on one JSON object. Keep each declaration available to
// the UI, which knows which node kinds have resolved formatting.
const definitions = schema.definitions;
const { oneOf, anyOf, ...fields } = definitions.NodeView;
definitions.NodeFields = fields;
definitions.NodeData = { oneOf };
definitions.NodeFormatting = { anyOf: anyOf.filter(choice => choice.properties) };
definitions.NodeView = {
  allOf: [{ $ref: "#/definitions/NodeFields" }, { $ref: "#/definitions/NodeData" }],
};
// Layout correlates these optional fields with the node's discriminator.
schema.properties.formatting = { $ref: "#/definitions/NodeFormatting" };

// json-schema-to-typescript gives allOf precedence over sibling properties.
// Preserve the discriminator serde adds beside a flattened variant payload.
function expandIntersections(value) {
  if (!value || typeof value !== "object") return;
  for (const child of Object.values(value)) expandIntersections(child);
  if (value.allOf && value.properties) {
    value.allOf.push({ type: "object", properties: value.properties, required: value.required });
    delete value.properties;
    delete value.required;
  }
}
expandIntersections(schema);

const output = await compile(schema, "WebApi", {
  additionalProperties: false,
  bannerComment: "// Generated by node web/generate-types.mjs from the Rust serde types.",
  format: true,
});
const path = new URL("./wire.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== output) throw new Error("Regenerate web/wire.generated.ts");
} else {
  writeFileSync(path, output);
}
